import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { policy, policyVersion } from './asset-policy.mjs';

const security = `    add_header X-Content-Type-Options nosniff always;
    add_header Referrer-Policy strict-origin-when-cross-origin always;
    add_header X-Frame-Options DENY always;
    add_header Strict-Transport-Security "max-age=31536000" always;`;
const mapsCSP = `    add_header Content-Security-Policy "default-src 'none'; script-src 'self' 'unsafe-inline' data:; style-src 'self' 'unsafe-inline'; img-src 'self' data: blob:; connect-src 'self' data: blob:; worker-src 'self' blob:; object-src 'none'; base-uri 'none'; frame-ancestors 'none'; form-action 'none'" always;`;
function location(match, target, cache, maps = false) {
  return `location ${match} {
    alias ${target};
    index index.html;
    autoindex off;
    if ($uri ~ "(^|/)\\.") { return 404; }
    etag on;
    expires off;
    brotli_static on;
    gzip_static on;
    gzip_vary on;
    add_header X-PIL-Asset-Policy "${policyVersion}" always;
    add_header Cache-Control "${policy.cache[cache]}"${cache === 'immutable' ? '' : ' always'};
${security}
${maps ? mapsCSP + '\n' : ''}}\n`;
}
export function renderNginx() {
  let config = '# Generated by npm --prefix deploy run policy:generate; policy ' + policyVersion + '\n';
  for (const prefix of policy.prefixes) {
    config += `location = ${prefix} { return 308 ${prefix}/$is_args$args; }\n`;
    config += `location = ${prefix}/3d { return 308 ${prefix}/3d/$is_args$args; }\n`;
    config += location('^~ ' + prefix + '/' + policy.immutableDirectory + '/', '/srv/pkuidv/tactical/assets/client/', 'immutable');
    config += location('^~ ' + prefix + '/3d/releases/', '/srv/pkuidv/tactical/assets/', 'immutable', true);
    for (const name of ['__release.json', 'asset-manifest.json', '3d/__release.json']) {
      config += location('= ' + prefix + '/' + name, '/srv/pkuidv/tactical/current/' + name, 'metadata');
    }
    config += location('^~ ' + prefix + '/3d/', '/srv/pkuidv/tactical/current/3d/runtime/', 'entry', true);
    config += location('^~ ' + prefix + '/', '/srv/pkuidv/tactical/current/', 'entry');
  }
  config += 'location = /maps-3d { return 404; }\nlocation ^~ /maps-3d/ { add_header Cache-Control "no-store" always; return 404; }\n';
  return config;
}
export function renderCloudflare() {
  const owned = policy.prefixes.map(p => `starts_with(http.request.uri.path, "${p}/")`).join(' or ');
  const immutable = policy.prefixes.flatMap(p => [p + '/' + policy.immutableDirectory + '/', p + '/3d/releases/']).map(p => `starts_with(http.request.uri.path, "${p}")`).join(' or ');
  return [
    { ref: 'pil_tactical_mutable_revalidate', description: 'PIL policy: entry pages and unversioned files always revalidate', expression: `(http.host eq "pkuidv.com" and (${owned}) and not (${immutable}))`, action: 'set_cache_settings', action_parameters: { cache: false, browser_ttl: { mode: 'respect_origin' } }, enabled: true },
    { ref: 'pil_tactical_immutable_assets', description: 'PIL policy: content snapshots and 3D releases are immutable', expression: `(http.host eq "pkuidv.com" and http.request.method in {"GET" "HEAD"} and (${immutable}))`, action: 'set_cache_settings', action_parameters: { cache: true, browser_ttl: { mode: 'respect_origin' }, edge_ttl: { mode: 'respect_origin' }, respect_strong_etags: false }, enabled: true },
  ];
}
export async function renderPolicy(check = false) {
  const files = { 'tactical.nginx.conf': renderNginx(), 'cloudflare-cache-rules.json': JSON.stringify(renderCloudflare(), null, 2) + '\n' };
  const directory = new URL('../generated/', import.meta.url);
  if (!check) await mkdir(directory, { recursive: true });
  for (const [name, value] of Object.entries(files)) {
    if (check) { if (await readFile(new URL(name, directory), 'utf8') !== value) throw Error('Generated policy is stale: ' + name); }
    else await writeFile(new URL(name, directory), value);
  }
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await renderPolicy(process.argv.includes('--check'));
